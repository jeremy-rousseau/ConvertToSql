from datetime import date, datetime
from decimal import Decimal

from qgis.core import QgsVariantUtils
from PyQt5.QtCore import QDate, QDateTime, QTime

def quote_identifier(identifier):
    """Quote a single PostgreSQL identifier."""
    identifier = str(identifier)
    if not identifier:
        raise ValueError("SQL identifiers cannot be empty.")

    return '"' + identifier.replace('"', '""') + '"'


def quote_table_name(table_name):
    """Quote a table name, optionally including its schema."""
    parts = table_name.split(".")

    if any(not part for part in parts):
        raise ValueError(
            "Use a table name such as 'my_table' or 'my_schema.my_table'."
        )

    return ".".join(quote_identifier(part) for part in parts)


def sql_value(value):
    """Convert a Python value into a PostgreSQL SQL literal."""
    if value is None or QgsVariantUtils.isNull(value):
        return "NULL"

    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"

    if isinstance(value, (int, float, Decimal)):
        return str(value)

    if isinstance(value, QDateTime):
        return "'" + value.toString("yyyy-MM-dd HH:mm:ss") + "'"

    if isinstance(value, QDate):
        return "'" + value.toString("yyyy-MM-dd") + "'"

    if isinstance(value, QTime):
        return "'" + value.toString("HH:mm:ss") + "'"

    if isinstance(value, datetime):
        return "'" + value.isoformat(sep=" ").replace("'", "''") + "'"

    if isinstance(value, date):
        return "'" + value.isoformat() + "'"

    text = str(value)
    return "'" + text.replace("'", "''") + "'"


def build_insert_statement(
    table_name,
    field_names,
    values,
    geometry_wkt,
    srid,
    geometry_column="geom",
):
    """Build one INSERT statement with a PostGIS geometry expression."""

    if len(field_names) != len(values):
        raise ValueError(
            "The number of field names must match the number of values."
        )

    if srid is None or int(srid) < 0:
        raise ValueError("A valid target SRID is required.")

    column_names = [
        quote_identifier(name) for name in field_names
    ]
    column_names.append(quote_identifier(geometry_column))

    sql_values = [sql_value(value) for value in values]

    if geometry_wkt is None:
        geometry_expression = "NULL"
    else:
        escaped_wkt = geometry_wkt.replace("'", "''")
        geometry_expression = (
            "ST_GeomFromText("
            + sql_value(escaped_wkt)
            + ", "
            + str(int(srid))
            + ")"
        )

    sql_values.append(geometry_expression)

    return (
        "INSERT INTO "
        + quote_table_name(table_name)
        + " ("
        + ", ".join(column_names)
        + ") VALUES ("
        + ", ".join(sql_values)
        + ");"
    )
