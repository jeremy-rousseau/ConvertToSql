from qgis.core import (
    QgsCoordinateTransform,
    QgsGeometry,
)

from .sql_generator import build_insert_statement


def convert_features(
    source,
    field_names,
    table_name,
    target_crs,
    context,
    feedback,
    geometry_column="geom",
):
    """Yield one SQL INSERT statement for each source feature."""

    source_crs = source.sourceCrs()
    requires_transform = source_crs != target_crs

    transform = None

    if requires_transform:
        transform = QgsCoordinateTransform(
            source_crs,
            target_crs,
            context.transformContext(),
        )

    srid = target_crs.postgisSrid()

    if srid <= 0:
        raise ValueError(
            "The target CRS must have a valid PostGIS SRID."
        )

    total_features = source.featureCount()
    progress_step = (
        100.0 / total_features if total_features else 0
    )

    for current, feature in enumerate(source.getFeatures()):
        if feedback.isCanceled():
            break

        # Read attribute values in the requested field order.
        values = [
            feature[name]
            for name in field_names
        ]

        # Copy the geometry so the source feature is not modified.
        geometry = QgsGeometry(feature.geometry())

        if not geometry.isNull() and requires_transform:
            geometry.transform(transform)

        geometry_wkt = (
            None
            if geometry.isNull()
            else geometry.asWkt(17)
        )

        yield build_insert_statement(
            table_name=table_name,
            field_names=field_names,
            values=values,
            geometry_wkt=geometry_wkt,
            srid=srid,
            geometry_column=geometry_column,
        )

        feedback.setProgress(
            int((current + 1) * progress_step)
        )
