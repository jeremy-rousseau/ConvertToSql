import processing
from qgis.PyQt.QtCore import QCoreApplication
import os
from qgis.PyQt.QtGui import QIcon
from qgis.core import (QgsProcessing,
                       QgsProcessingParameterCrs,
                       QgsProcessingAlgorithm,
                       QgsProcessingParameterFeatureSource,
                       QgsProcessingParameterString,
                       QgsProcessingException,
                       QgsProcessingParameterFileDestination,
                       QgsProcessingParameterFieldMapping,
                       QgsProcessingUtils,)

from .core.converter import convert_features

class ConvertToSqlInsertAlgorithm(QgsProcessingAlgorithm):
    """
    Convert a vector layer into PostgreSQL/PostGIS INSERT statements.
    """

    # Constants used to refer to parameters and outputs. They will be
    # used when calling the algorithm from another algorithm, or when
    # calling from the QGIS console.

    OUTPUT = 'OUTPUT'
    FIELD_MAPPING = 'FIELD_MAPPING'
    TABLE_NAME = 'TABLE_NAME'
    TARGET_CRS = 'TARGET_CRS'
    INPUT = 'INPUT'

    def initAlgorithm(self, config):
        """
        Define the algorithm parameters.
        """

        # Input vector layer
        self.addParameter(
            QgsProcessingParameterFeatureSource(
                self.INPUT,
                self.tr('Input layer'),
                [QgsProcessing.TypeVectorAnyGeometry],
            )
        )

        # Mapping between input fields and SQL columns
        self.addParameter(
            QgsProcessingParameterFieldMapping(
                self.FIELD_MAPPING,
                self.tr('Field Mapping'),
                parentLayerParameterName=self.INPUT,
            )
        )

        # Target SQL table name
        self.addParameter(
            QgsProcessingParameterString(
                self.TABLE_NAME,
                self.tr('SQL table name'),
                defaultValue='schema.table',
            )
        )

        # Target coordinate reference system
        self.addParameter(
            QgsProcessingParameterCrs(
                self.TARGET_CRS,
                self.tr('Target coordinate reference system'),
                defaultValue=None,
                optional=True,
            )
        )

        # Path to the generated SQL file
        self.addParameter(
            QgsProcessingParameterFileDestination(
                self.OUTPUT,
                self.tr('Output SQL file'),
                fileFilter="SQL files (*.sql)",
            )
        )

    def processAlgorithm(self, parameters, context, feedback):
        """
        Generate the SQL file.
        """

        source = self.parameterAsSource(
            parameters,
            self.INPUT,
            context,
        )

        if source is None:
            raise QgsProcessingException(
                self.tr("The input layer is invalid.")
            )

        # Refactor the source fields using the configured mapping.
        feedback.pushInfo(
            self.tr("Refactoring input fields...")
        )

        mapping = parameters.get(self.FIELD_MAPPING)

        refactor_result = processing.run(
            "native:refactorfields",
            {
                "INPUT": parameters[self.INPUT],
                "FIELDS_MAPPING": mapping,
                "OUTPUT": QgsProcessing.TEMPORARY_OUTPUT,
            },
            context=context,
            feedback=feedback,
            is_child_algorithm=True,
        )

        refactored_layer = QgsProcessingUtils.mapLayerFromString(
            refactor_result["OUTPUT"],
            context,
        )

        if refactored_layer is None:
            raise QgsProcessingException(
                self.tr("Could not retrieve the refactored layer.")
            )

        if feedback.isCanceled():
            return {}


        table_name = self.parameterAsString(
            parameters,
            self.TABLE_NAME,
            context,
        ).strip()

        if not table_name:
            raise QgsProcessingException(
                self.tr("The SQL table name cannot be empty.")
            )

        target_crs = self.parameterAsCrs(
            parameters,
            self.TARGET_CRS,
            context,
        )

        # Fall back to the source layer CRS if no target CRS was selected.
        if not target_crs.isValid():
            target_crs = source.sourceCrs()

        if not target_crs.isValid():
            raise QgsProcessingException(
                self.tr("Neither the target CRS nor the source layer CRS is valid.")
            )

        output_path = self.parameterAsFileOutput(
            parameters,
            self.OUTPUT,
            context,
        )

        if not output_path:
            raise QgsProcessingException(
                self.tr("The output SQL file path is invalid.")
            )

        field_names = [
            field.name()
            for field in refactored_layer.fields()
        ]

        if "geom" in field_names:
            raise QgsProcessingException(
                self.tr(
                    "The input layer already contains a field named "
                    "'geom'. Rename that field before exporting."
                )
            )

        feedback.pushInfo(
            self.tr("Preparing SQL export...")
        )

        try:
            with open(
                output_path,
                "w",
                encoding="utf-8",
                newline="\n",
            ) as output_file:

                output_file.write("BEGIN;\n\n")

                for statement in convert_features(
                    source=refactored_layer,
                    field_names=field_names,
                    table_name=table_name,
                    target_crs=target_crs,
                    context=context,
                    feedback=feedback,
                    geometry_column="geom",
                ):
                    if feedback.isCanceled():
                        break

                    output_file.write(statement + "\n")

                if feedback.isCanceled():
                    output_file.write("\nROLLBACK;\n")
                    feedback.pushWarning(
                        self.tr(
                            "Export cancelled. The SQL file contains "
                            "a partial export followed by ROLLBACK."
                        )
                    )
                else:
                    output_file.write("\nCOMMIT;\n")

        except (OSError, ValueError) as error:
            raise QgsProcessingException(
                self.tr("Could not generate the SQL file: ")
                + str(error)
            )

        feedback.pushInfo(
            self.tr("SQL file created: ") + output_path
        )

        return {self.OUTPUT: output_path}

